def __getattr__(name: str):
    """Serve live mutable session/cache globals from their owning modules."""
    if name in ("_session", "_analysis"):
        return getattr(_session_mod, name)
    if name == "_warp_reference":
        return _warping_mod._warp_reference
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


