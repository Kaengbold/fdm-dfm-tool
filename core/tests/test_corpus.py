"""Regression corpus (T-003): typical hobby parts, their known good orientation and key findings.

The parts are generated by tools/make_corpus.py. A change that moves a top pick or loses a
finding here needs a reason, not just a new expected value.
"""

from pathlib import Path

import numpy as np
import pytest

from fdmcore import api

CORPUS = Path(__file__).parent / "corpus"
Y = [[0, 1, 0], [0, -1, 0]]
UP = [[0, 0, 1]]

# name: (good "up" directions, findings that must be there, findings that must not)
CASES = {
    "shelf_bracket": (Y, set(), {"long_bridge", "support_marks"}),  # on its side: the gusset profile is flat
    "drawer_handle": (Y, set(), {"long_bridge"}),  # on its side, not posts down under a bridged bar
    "pegboard_hook": (Y, set(), {"support_marks"}),  # flat: layers follow the hook
    "knob": (UP, {"bridge_sag"}, {"support_marks"}),  # skirt down; the blind shaft hole's ceiling sags
    "pencil_cup": (UP, set(), {"support_marks", "trapped_support"}),
    "spool_hub": (UP, set(), {"support_marks"}),  # flange on the bed
    "tray": (UP, {"warping"}, {"support_marks", "trapped_support"}),  # long flat PLA base: corners can lift
    "text_sign": (UP, set(), {"support_marks"}),  # plate down, letters up
    "gear": (UP, set(), {"support_marks"}),
    # Standing it tips, wobbles and snaps along the layers: these must be reported. Lying down
    # isn't better as modelled (a round pin touches the bed in a line and needs support all along),
    # so the orientation itself isn't pinned here (T-190).
    "tall_pin": (None, {"tipping_risk", "tall_thin_feature", "weak_upright_pin"}, set()),
}


@pytest.mark.skipif(not CORPUS.exists(), reason="run tools/make_corpus.py")
@pytest.mark.parametrize("name", CASES)
def test_corpus_part(name):
    good_ups, must, must_not = CASES[name]
    api.load((CORPUS / f"{name}.stl").read_bytes(), name)
    options = api.orientations()["orientations"]
    top = options[0]
    pick = (top["support_g"], -top["bed_area_mm2"], top["height_mm"])
    for option in options[1:]:
        alternative = (option["support_g"], -option["bed_area_mm2"], option["height_mm"])
        assert not (all(left <= right for left, right in zip(alternative, pick))
                    and any(left < right for left, right in zip(alternative, pick))), (name, top, option)
    if good_ups is not None:
        assert any(np.allclose(top["up"], u, atol=1e-6) for u in good_ups), f"{name}: top pick up={top['up']}"
    rules = {f["rule"] for f in api.check(top["up"])["findings"]}
    assert must <= rules, f"{name}: missing {must - rules}"
    assert not rules & must_not, f"{name}: unexpected {rules & must_not}"


def test_standing_tall_on_a_narrow_base_is_penalised():
    from fdmcore.mesh import load_stl
    from fdmcore.orientation import evaluate

    pin = load_stl((CORPUS / "tall_pin.stl").read_bytes())
    assert evaluate(pin, [0, 0, 1]).terms["stability"] == pytest.approx(1.0)  # 80 mm on a Ø10 foot
    assert evaluate(load_stl((CORPUS / "spool_hub.stl").read_bytes()), [0, 0, 1]).terms["stability"] == 0.0


def test_cooling_finding_names_the_settings():
    api.load((CORPUS / "tall_pin.stl").read_bytes(), "tall_pin")
    cool = {f["rule"]: f for f in api.check([0, 0, 1], profile={"material": "petg"})["findings"]}["small_layers_cooling"]
    # The slicer's slow-down stops at the minimum print speed: the finding says how low to set it.
    assert cool["metrics"]["min_speed_mm_s"] in (5, 3, 2)
    assert "minimum print speed" in cool["detail"]
