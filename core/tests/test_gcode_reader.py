"""The G-code reader on real slicer output (T-471): speeds, fans, objects, firmware, why lines are slower.

Fixtures: one small part (block, overhanging tab, thin pin on top) sliced by OrcaSlicer, PrusaSlicer and
Bambu Studio (tools/make_gcode_fixtures.py).
"""

import gzip
import json
import tracemalloc
import zipfile
from pathlib import Path

import numpy as np
import pytest

from fdmcore import api, gcode
from fdmcore.gcode import BRIDGE, LAYER_TIME, OVERHANG, SMALL_PERIMETER, UNKNOWN, VOLUMETRIC_CAP

FIXTURES = Path(__file__).parent / "gcode"
PIN_Z = 6.4  # above this only the Ø3 mm pin prints (the block is 6 mm; PrusaSlicer layers are 0.3 mm): layers far shorter than the minimum layer time


def read(name: str) -> bytes:
    if name == "bambu":
        return (FIXTURES / "bambu.gcode.3mf").read_bytes()
    return gzip.decompress((FIXTURES / f"{name}.gcode.gz").read_bytes())


def parsed(name: str) -> gcode.Toolpath:
    if name == "bambu":
        with zipfile.ZipFile(FIXTURES / "bambu.gcode.3mf") as z:
            return gcode.parse(z.read("Metadata/plate_1.gcode"), json.loads(z.read("Metadata/project_settings.config")))
    return gcode.parse(read(name))


def named(tp, feature: str) -> np.ndarray:
    return tp.feature == tp.features.index(feature)


@pytest.mark.parametrize("name, slicer, firmware", [("orca", "orca", "bambu"), ("prusa", "prusa", "marlin"),
                                                    ("bambu", "bambu", "bambu")])
def test_every_slowdown_has_a_cause(name, slicer, firmware):
    tp = parsed(name)
    assert (tp.slicer, tp.firmware) == (slicer, firmware)
    assert len(tp.speed) == len(tp.volume) == len(tp.cause) == len(tp.part_fan)
    slowed = tp.speed < tp.set_speed * 0.97
    assert slowed.sum() > 100
    assert np.all(tp.cause[slowed] > 0)
    assert not np.any(tp.cause == UNKNOWN)
    assert not np.any(slowed & (tp.cause == 0))
    pin = tp.p1[:, 2] > PIN_Z  # tiny layers: the slicer slows them to its minimum speed for cooling
    assert np.all(tp.cause[pin & tp.part()] == LAYER_TIME)
    min_speed = float(tp.settings["slow_down_min_speed" if name != "prusa" else "min_print_speed"].split(",")[0])
    assert np.allclose(tp.speed[pin & tp.part()], min_speed, atol=0.1)
    assert gcode.time_lost(tp)[LAYER_TIME] > 0


def test_orca_flow_limit_overhangs_and_bridges():
    tp = parsed("orca")
    assert tp.settings["outer_wall_speed"] == "200"
    first_solid = (tp.layer == 1) & named(tp, "Inner wall")  # 300 mm/s set, 16 mm³/s filament limit
    assert np.all(tp.cause[first_solid] == VOLUMETRIC_CAP)
    area = tp.volume / np.linalg.norm(tp.p1 - tp.p0, axis=1)
    assert np.allclose((tp.speed * area)[first_solid], 16, rtol=0.03)
    assert np.all(tp.cause[named(tp, "Bridge")] == BRIDGE)
    assert np.all(tp.cause[named(tp, "Internal Bridge")] == BRIDGE)
    walls = (tp.layer == 20) & named(tp, "Outer wall")  # under the tab: 50 mm/s (overhang_2_4_speed)
    assert set(tp.cause[walls & (tp.speed < 60)]) == {OVERHANG}


def test_prusa_cooling_slows_the_fastest_lines_first():
    tp = parsed("prusa")
    layer = tp.layer == 5
    infill, outer = layer & named(tp, "Internal infill"), layer & named(tp, "External perimeter")
    assert np.all(tp.cause[infill] == LAYER_TIME) and np.all(tp.speed[infill] < 80)
    assert np.all(tp.cause[outer] == 0)  # 30 mm/s, below where the layer was capped


def test_bambu_sliced_plate():
    tp = parsed("bambu")
    assert np.all(tp.cause[named(tp, "Overhang wall")] == OVERHANG)
    assert np.all(tp.cause[named(tp, "Bridge")] == BRIDGE)
    assert tp.objects == ("8",) and np.all(tp.obj[tp.part()] == 0)
    # Bambu firmware: M106 P1 is the part fan too, P2 the aux fan, P3 the chamber fan.
    assert tp.fan_names[:1] == ("part",) and {"P2", "P3"} <= set(tp.fan_names)
    assert tp.part_fan[tp.layer > 3].max() == pytest.approx(1.0)
    assert len(tp.retracts["t"]) and np.all(np.diff(tp.travel["t0"]) >= 0)


def test_load_gcode_reads_the_sliced_plate():
    api.load((FIXTURES / "part.stl").read_bytes(), "fixture")
    info = api.load_gcode(read("bambu"), [0, 0, 1])
    assert info["slicer"] == "bambu" and info["firmware"] == "bambu"
    assert info["slowdown_min"]["layer_time"] > 0 and "unknown" not in info["slowdown_min"]


def test_fans_objects_tools_and_pressure_advance():
    text = "\n".join([
        "; generated by OrcaSlicer", "M83", "; FEATURE: Outer wall",
        "EXCLUDE_OBJECT_START NAME=left", "SET_PRESSURE_ADVANCE ADVANCE=0.04", "M106 S127.5",
        "G1 X10 Y0 Z0.2 F600", "G1 X20 Y0 E0.5 F1200", "G10", "G1 X30 Y10 F9000", "G11",
        "SET_FAN_SPEED FAN=aux SPEED=0.7", "EXCLUDE_OBJECT_END NAME=left",
        "T1", "M486 S3", "M900 K0.02", "M106 P1 S255", "G1 X40 Y10 E0.5 F1200", "M486 S-1",
        "G1 X50 Y10 E0.5 F1200",
        "; retraction_length = 0.8", "; gcode_flavor = klipper",
    ])
    tp = gcode.parse(text)
    assert tp.firmware == "klipper"
    assert tp.objects == ("left", "3") and tp.obj.tolist() == [0, 1, -1]
    assert tp.tool.tolist() == [0, 1, 1]
    assert tp.part_fan.tolist() == pytest.approx([0.5, 0.5, 0.5])  # P1 is no part fan on Klipper
    assert [tp.fan_names[f] for f in tp.fans["fan"]] == ["part", "aux", "P1"]
    assert tp.pressure_advance["value"].tolist() == [0.04, 0.02]
    assert tp.pressure_advance["line"].tolist() == [0, 1]
    assert tp.retracts["mm"].tolist() == [-0.8, 0.8]  # firmware retraction: its length from the settings
    assert tp.speed.tolist() == pytest.approx([20, 20, 20])
    assert tp.travel["speed"][-1] == pytest.approx(150) and tp.travel["line"][-1] == 1


def test_small_perimeters_and_settings_at_the_end():
    """PrusaSlicer writes its settings after the moves; percentages refer to other settings."""
    loop = [f"G1 X{100 + 2 * np.cos(a):.3f} Y{100 + 2 * np.sin(a):.3f} E0.02 F900" for a in np.linspace(0, 2 * np.pi, 13)[1:]]
    text = "\n".join([
        "; generated by PrusaSlicer 2.8.0", "M83", ";LAYER_CHANGE", ";Z:0.2", ";TYPE:Perimeter", "G1 X0 Y0 Z0.2 F600",
        "G1 X40 Y0 E1 F1800",  # first layer: first_layer_speed 50 % of 60
        ";LAYER_CHANGE", ";Z:0.4", "G1 Z0.4", "G1 X0 Y0 E1 F3600", ";TYPE:External perimeter", "G1 X102 Y100 F9000", *loop,
        "; prusaslicer_config = begin", "; perimeter_speed = 60", "; external_perimeter_speed = 50%",
        "; small_perimeter_speed = 15", "; first_layer_speed = 50%", "; min_print_speed = 10", "; gcode_flavor = marlin2",
        "; prusaslicer_config = end",
    ])
    tp = gcode.parse(text)
    assert tp.slicer == "prusa" and tp.firmware == "marlin"
    assert tp.set_speed.tolist()[:2] == pytest.approx([30, 60])
    assert tp.cause.tolist() == [0, 0] + [SMALL_PERIMETER] * 12
    assert np.all(tp.set_speed[2:] == pytest.approx(30))


def test_big_files_are_read_in_pieces():
    """The text is never held whole, only the numbers each line needs."""
    def pieces(n_layers=50):
        yield b"; generated by OrcaSlicer\nM83\n; FEATURE: Sparse infill\n"
        for k in range(n_layers):
            yield f";LAYER_CHANGE\nG1 Z{0.2 * (k + 1):.2f} F600\n".encode()
            yield "".join(f"G1 X{60 + (i % 2) * 80:.3f} Y{60 + i * 0.04:.3f} E0.2345 F9000\n" for i in range(4000)).encode()

    tracemalloc.start()
    try:
        tp = gcode.parse(pieces())
        peak = tracemalloc.get_traced_memory()[1]
    finally:
        tracemalloc.stop()
    assert len(tp.volume) == 200_000
    # ~75 bytes a line for the result, a few MB for the piece being read: a 200 MB G-code (~6 million
    # lines) needs well under 1 GB. Holding its text as a list of lines would take ~600 MB on its own.
    assert peak < 120 * len(tp.volume) + 8e6
