"""How much each spot matters (T-475): from the strength check's loads, else guessed from the shape."""

import gzip
from pathlib import Path

import numpy as np
import pytest

from fdmcore import api, gcode, importance, kinematics, thermal
from fdmcore.profile import Profile

SAMPLES = Path(__file__).parents[2] / "web" / "samples"
FIXTURES = Path(__file__).parent / "gcode"


def voxels(r: dict) -> tuple[np.ndarray, np.ndarray, list[str]]:
    pts = np.frombuffer(r["points"], np.float32).reshape(-1, 3)
    reasons = [r["reasons"][i] for i in np.frombuffer(r["reason"], np.uint8)]
    return pts, np.frombuffer(r["weight"], np.float32), reasons


def inside(bbox, xy) -> bool:
    return all(bbox[0][i] <= xy[i] <= bbox[1][i] for i in range(2))


def test_without_loads_the_pins_and_their_roots_matter_most():
    """The feature test part (T-389): the Ø3 mm pin and the thin slot walls stand on the base plate; their
    roots weigh most, the infill inside the plate least, and it says the weights are a guess."""
    api.load((SAMPLES / "feature_test.stl").read_bytes(), "feature_test.stl")
    r = api.importance([0, 0, 1])
    assert r["guessed"] and "Add the loads" in r["note"]
    pts, w, why = voxels(r)
    pin = pts[pts[:, 2] > 30][:, :2].mean(axis=0)  # only the pin reaches this high
    roots = [a for a in r["areas"] if a["reason"] == "root"]
    assert r["areas"][0]["reason"] == "root" and any(inside(a["bbox"], pin) for a in roots)
    assert any(a["bbox"][0][2] < 6 < a["bbox"][1][2] for a in roots)  # where the pin meets the 4 mm plate
    assert w.max() == 1 and {"pin", "corner", "hole", "wall", "inside"} <= set(why)
    deep = np.array([x == "inside" for x in why])
    assert np.allclose(w[deep], r["floor"]) and r["areas"][0]["text"].startswith("Root")


def test_with_a_load_the_bracket_root_matters_most():
    """An L-bracket held by its base, pushed sideways at the top of its upright: the upright's root carries
    the most across its layers, the top of the upright and the far end of the base hardly anything."""
    api.load((SAMPLES / "l_bracket.stl").read_bytes(), "l_bracket.stl")
    loads = [{"region": 2, "kind": "fixed"}, {"region": 5, "kind": "force", "kg": 5, "direction": [1, 0, 0]}]
    r = api.importance([0, 0, 1], loads)
    assert not r["guessed"] and r["note"] is None
    pts, w, why = voxels(r)
    x, z = pts[np.argmax(w)][[0, 2]]
    assert x < -24 and 2 < z < 12  # the upright is x -30..-25, the base 5 mm thick
    assert r["areas"][0]["reason"] == "load" and r["areas"][0]["point"][2] < 12
    upper, far = (pts[:, 0] < -24) & (pts[:, 2] > 20) & (pts[:, 2] < 32), pts[:, 0] > 15  # not next to the load
    assert w.max() > 0.8 and w[upper].max() < 0.75 * w.max() and np.allclose(w[far], r["floor"])
    tagged = api.importance([0, 0, 1], loads, intents=[{"kind": "load_bearing", "point": [25, 0, 2.5], "radius": 3}])
    _, w2, why2 = voxels(tagged)
    assert w2[far].max() == 1 and "tag" in why2


def slab(fan: int = 255) -> gcode.Toolpath:
    """A 6 mm thick wall, 25 layers, 60 mm lines at 50 mm/s (as in test_heat_window)."""
    w, lh = 0.45, 0.2
    e = w * lh / (np.pi * 1.75**2 / 4)
    out = ["; generated by OrcaSlicer", "M83", f"M106 S{fan}"]
    for k in range(25):
        out += [";LAYER_CHANGE", f"G1 Z{(k + 1) * lh:.2f} F600", "; FEATURE: Inner wall"]
        for i, y in enumerate(np.arange(w / 2, 6.0, w)):
            x0, x1 = (0, 60) if i % 2 == 0 else (60, 0)
            out += [f"G1 X{x0:.3f} Y{y:.3f} F6000", f"G1 X{x1:.3f} Y{y:.3f} E{60 * e:.5f} F3000"]
    return gcode.parse("\n".join(out))


def test_weight_moves_only_the_bonding_goal():
    """Under full fan the wall bonds too little for a spot that matters, but enough for one that doesn't;
    the sag limit is the same either way."""
    tp = slab()
    p = Profile.from_dict({"material": "pla", "printer": "bambu_p1s"})
    h = thermal.simulate(tp, kinematics.timing(tp), p)
    floor = importance.settings()["floor"]
    lax, strict = (thermal.window(h, p, weight=np.full(len(h.layer), v)) for v in (floor, 1.0))
    plain, marked = thermal.window(h, p), thermal.window(h, p, {"load_bearing": np.ones(len(h.layer), bool)})
    body = h.layer >= 5
    assert strict["too_cold"][body].mean() > 0.8 and not lax["too_cold"][body].any()
    assert np.array_equal(strict["min_bond"], marked["min_bond"])  # marked load-bearing = weight 1
    assert (lax["min_bond"] < plain["min_bond"]).all() and (plain["min_bond"] < strict["min_bond"]).all()
    assert np.array_equal(lax["limit_c"], strict["limit_c"])


def test_bond_goal_steps():
    cfg = importance.settings()
    goal = 0.25
    at = importance.bond_goal(goal, np.array([cfg["floor"], cfg["ordinary"], 1.0]))
    assert at == pytest.approx([goal * cfg["bond_relax"], goal, goal + cfg["bond_strict_shift"]])


def test_heat_model_weighs_its_spots():
    """Without loads the heat model uses the guessed weights: the fixture's pin matters more than the
    block's inside, and the result says it is a guess."""
    api.load((FIXTURES / "part.stl").read_bytes(), "fixture")
    api.load_gcode((FIXTURES / "bambu.gcode.3mf").read_bytes(), [0, 0, 1])
    r = api.heat_model([0, 0, 1])
    w = np.frombuffer(r["importance"], np.float32)
    why = np.frombuffer(r["importance_reason"], np.uint8)
    pts = np.frombuffer(r["points"], np.float32).reshape(-1, 3)
    assert r["guessed"] and len(w) == len(why) == r["spots"]
    assert np.median(w[pts[:, 2] > 6.4]) > 0.8  # the Ø3 mm pin above the 6 mm block
    assert r["reasons"][np.bincount(why[pts[:, 2] < 5]).argmax()] in ("inside", "wall")

    # With a load (the bottom held, the pin's top pushed sideways) the strength check decides instead.
    mesh = api._require().mesh
    normals, areas = mesh.normals_and_areas()
    regions = api._require().regions
    top_z = mesh.triangles[:, :, 2].mean(axis=1)
    bottom = int(np.bincount(regions[normals[:, 2] < -0.99], weights=areas[normals[:, 2] < -0.99]).argmax())
    tip = int(regions[np.flatnonzero((normals[:, 2] > 0.99) & (top_z > 9.9))[0]])
    loads = [{"region": bottom, "kind": "fixed"}, {"region": tip, "kind": "force", "kg": 1, "direction": [1, 0, 0]}]
    loaded = api.heat_model([0, 0, 1], loads=loads)
    w = np.frombuffer(loaded["importance"], np.float32)
    top = pts[np.argmax(w)]  # the peg's root: where it meets the block
    assert not loaded["guessed"] and w.max() > 0.8 and 5 < top[2] < 8.5
    assert np.linalg.norm(top[:2] - pts[pts[:, 2] > 8][:, :2].mean(axis=0)) < 3
