"""Fine heat detail only where it matters (T-583)."""

import numpy as np

from fdmcore import api, gcode, kinematics, thermal
from fdmcore.profile import Profile
from test_hold import box

SIZE, BASE, PIN_TOP, AT = 36.0, 4.0, 14.0, 100.0  # a solid plate with a Ø3 mm pin in the middle, placed at (100, 100)


def plate_with_pin(size: float = SIZE) -> str:
    lh, w = 0.2, 0.45
    e_mm = w * lh / (np.pi * 1.75**2 / 4)
    out = ["; generated by OrcaSlicer", "M83", "M106 S255"]
    for k in range(int(round(PIN_TOP / lh))):
        z = (k + 1) * lh
        out += [";LAYER_CHANGE", f"G1 Z{z:.2f} F600"]
        if z <= BASE:
            out.append("; FEATURE: Internal solid infill")
            for i, y in enumerate(np.arange(w / 2, size, w)):
                x0, x1 = (0, size) if i % 2 == 0 else (size, 0)
                out += [f"G1 X{x0 + AT:.3f} Y{y + AT:.3f} F12000", f"G1 X{x1 + AT:.3f} Y{y + AT:.3f} E{size * e_mm:.5f} F9000"]
            continue
        out.append("; FEATURE: Outer wall")
        for r in (1.3, 0.85):
            a = np.linspace(0, 2 * np.pi, 17)
            xs, ys = AT + size / 2 + r * np.cos(a), AT + size / 2 + r * np.sin(a)
            out.append(f"G1 X{xs[0]:.3f} Y{ys[0]:.3f} F12000")
            out += [f"G1 X{x1:.3f} Y{y1:.3f} E{np.hypot(x1 - x0, y1 - y0) * e_mm:.5f} F1800"
                    for x0, y0, x1, y1 in zip(xs, ys, xs[1:], ys[1:])]
    return "\n".join(out)


def test_a_detail_run_of_a_region_matches_the_full_fine_run():
    """Only the plastic in a box around the pin, with the whole print's timing and nozzle: the pin comes out
    as hot as in the fine run of the whole part, for a fraction of its cost."""
    tp = gcode.parse(plate_with_pin())
    tm = kinematics.timing(tp)
    p = Profile.from_dict({})
    c = AT + SIZE / 2
    full = thermal.simulate(tp, tm, p, "fine")
    part = thermal.simulate(tp, tm, p, "fine", region=(c - 8, c - 8, c + 8, c + 8))
    pin = lambda h: (h.z > BASE + 1) & (h.z < PIN_TOP - 1) & np.isfinite(h.cover_c)
    assert abs(np.median(part.cover_c[pin(part)]) - np.median(full.cover_c[pin(full)])) < 5
    assert len(part.layer) < 0.3 * len(full.layer) and part.seconds < full.seconds


def test_heat_model_focuses_on_the_pin():
    """The quick run finds the pin too hot; ``focus`` runs it again in fine detail in a box around it (not the
    whole plate), within twice the quick run's time, and the finding there comes from the fine run. A big
    plate: on a small part a fine run of the whole is cheap anyway."""
    big = 60.0
    api.load(box(big, big, PIN_TOP), "plate")  # the same size as the G-code: only the heat run matters here
    api.load_gcode(plate_with_pin(big).encode(), [0, 0, 1])
    quick = api.heat_model([0, 0, 1])
    r = api.heat_model([0, 0, 1], focus=True)
    assert len(r["focus"]) == 1
    area = r["focus"][0]
    (x0, y0), (x1, y1) = area["bbox"]
    assert x1 - x0 < big / 2 and y1 - y0 < big / 2  # around the pin, not the whole plate
    assert area["seconds"] <= quick["seconds"] and area["cover_c_max"]["fine"] > 100
    hot = [f for f in r["findings"] if f["rule"] == "heat_too_hot"]
    assert hot and all(f["bbox"][0][2] > BASE for f in hot)
    assert "focus" not in quick
