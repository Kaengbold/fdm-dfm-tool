"""Pause to put something into a closed pocket while printing (T-322)."""

import io
import zipfile

import numpy as np
import pytest

from fdmcore import api
from fdmcore.mesh import Mesh, to_binary_stl

from test_formats import box

UP = [0, 0, 1]


def _block(pocket_size=10.0) -> bytes:
    """30 × 30 × 10 mm block with a closed pocket (an inner shell) from z = 4 to 7 mm."""
    lo = 15 - pocket_size / 2
    pocket = box([0, 0, 0], 1, inward=True) * [pocket_size, pocket_size, 3] + [lo, lo, 4]
    return to_binary_stl(Mesh(np.concatenate([box([0, 0, 0], 1) * [30, 30, 10], pocket])))


def test_pocket_gets_a_pause_before_its_roof():
    api.load(_block(), "magnet_block")
    found = [f for f in api.check(UP, {"material": "pla"})["findings"] if f["rule"] == "pause_to_insert"]
    assert len(found) == 1
    f = found[0]
    layer_h = 0.2
    assert f["metrics"]["pause_z"] == pytest.approx(7.0 + layer_h) and f["severity"] == "info"
    assert f"layer {f['metrics']['layer']}" in f["detail"] and f["metrics"]["top_z"] == pytest.approx(7.0)


def test_long_roof_is_a_warning():
    api.load(_block(pocket_size=28.0), "wide")  # 28 mm roof, PLA bridges about 35 mm cleanly...
    f = next(f for f in api.check(UP, {"material": "pla"})["findings"] if f["rule"] == "pause_to_insert")
    assert f["severity"] == "info"
    api.load(to_binary_stl(Mesh(np.concatenate([box([0, 0, 0], 1) * [60, 60, 10],
                                                box([0, 0, 0], 1, inward=True) * [50, 50, 3] + [5, 5, 4]]))), "wider")
    f = next(f for f in api.check(UP, {"material": "pla"})["findings"] if f["rule"] == "pause_to_insert")
    assert f["severity"] == "warn" and "sag" in f["detail"]  # ...but not 50 mm


def test_plain_solid_has_no_pocket():
    api.load(to_binary_stl(Mesh(box([0, 0, 0], 20))), "cube")
    assert not [f for f in api.check(UP, {"material": "pla"})["findings"] if f["rule"] == "pause_to_insert"]


def test_export_carries_the_pause_for_each_slicer():
    api.load(_block(), "magnet_block")
    for slicer in ("orca", "prusa"):
        z = zipfile.ZipFile(io.BytesIO(api.export(UP, {}, {}, slicer=slicer, pauses=[7.0])))  # the pocket's top
        orca = z.read("Metadata/custom_gcode_per_layer.xml").decode()
        prusa = z.read("Metadata/Prusa_Slicer_custom_gcode_per_print_z.xml").decode()
        # Orca pauses at the nearest layer (7.0 + 0.6 × 0.2), Prusa at the next one up (just above 7.0).
        assert 'top_z="7.120" type="1"' in orca and 'print_z="7.010" type="1"' in prusa
    plain = zipfile.ZipFile(io.BytesIO(api.export(UP, {}, {})))
    assert "Metadata/custom_gcode_per_layer.xml" not in plain.namelist()


BAMBU = """; HEADER_BLOCK_START
; generated by BambuStudio 01.08.02.56
; HEADER_BLOCK_END
; CHANGE_LAYER
; Z_HEIGHT: 6.8
; LAYER_HEIGHT: 0.2
G1 E-.8 F1800
G1 X10 Y10 Z6.8 F7200
G1 E.8 F1800
G1 X20 Y10 E1.2
; CHANGE_LAYER
; Z_HEIGHT: 7
; LAYER_HEIGHT: 0.2
G1 E-.8 F1800
G1 X10 Y10 Z7 F7200
G1 E.8 F1800
G1 X20 Y10 E1.2
; CHANGE_LAYER
; Z_HEIGHT: 7.2
; LAYER_HEIGHT: 0.2
G1 E-.8 F1800
G17
G3 Z7.6 I1 J0 P1 F30000 ; spiral lift a little
G1 X10 Y10 Z7.2 F7200
G1 E.8 F1800
G1 X20 Y10 E1.2
; CONFIG_BLOCK_START
; machine_pause_gcode =
; CONFIG_BLOCK_END
"""


def _lines(data: bytes) -> list[str]:
    return data.decode().replace("\r\n", "\n").split("\n")


def test_pause_goes_into_a_sliced_file_before_the_roof():
    """Bambu Studio ignores the 3MF's pause: it goes into the sliced G-code instead, after the move up to
    the first layer over the pocket (filament pulled back) and before that layer prints."""
    r = api.pause_gcode(BAMBU.encode(), [7.0])
    assert r["pauses"] == [{"top": 7.0, "z": 7.2, "command": "M400 U1"}]  # empty setting: Bambu's own pause
    lines = _lines(r["data"])
    i = lines.index("M400 U1")
    assert lines[i - 1] == "; PAUSE_PRINTING" and lines[i - 2].startswith("G3 Z7.6") and lines[i + 1] == "G1 X10 Y10 Z7.2 F7200"
    assert lines.count("M400 U1") == 1 and lines.index("; Z_HEIGHT: 7.2") < i
    # Windows line endings stay, and PrusaSlicer's own pause command is used.
    prusa = BAMBU.replace("; CHANGE_LAYER", ";LAYER_CHANGE").replace("; Z_HEIGHT: ", ";Z:").replace("BambuStudio", "PrusaSlicer")
    prusa = prusa.replace("; machine_pause_gcode =", "; pause_print_gcode = M601").replace("\n", "\r\n")
    out = api.pause_gcode(prusa.encode(), [7.0])["data"].decode()
    assert "M601" in out and "\n" not in out.replace("\r\n", "")


def test_pause_in_a_bambu_sliced_3mf_keeps_its_checksum():
    """Bambu's .gcode.3mf: the G-code inside gets the pause and its .md5 is updated (the printer checks it);
    other files stay as they were."""
    import hashlib

    src = io.BytesIO()
    with zipfile.ZipFile(src, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("Metadata/plate_1.gcode", BAMBU)
        z.writestr("Metadata/plate_1.gcode.md5", hashlib.md5(BAMBU.encode()).hexdigest().upper())
        z.writestr("Metadata/slice_info.config", "<config/>")
    out = zipfile.ZipFile(io.BytesIO(api.pause_gcode(src.getvalue(), [7.0])["data"]))
    g = out.read("Metadata/plate_1.gcode")
    assert b"M400 U1" in g and out.read("Metadata/plate_1.gcode.md5").decode() == hashlib.md5(g).hexdigest().upper()
    assert out.read("Metadata/slice_info.config") == b"<config/>"
    assert out.getinfo("Metadata/plate_1.gcode").compress_type == zipfile.ZIP_DEFLATED


def test_pause_errors_say_what_to_do():
    with pytest.raises(ValueError, match="ends below"):  # another part, or another orientation
        api.pause_gcode(BAMBU.encode(), [20.0])
    with pytest.raises(ValueError, match="layer marks"):
        api.pause_gcode(b"G1 X1 Y1 E1\n", [7.0])
    with pytest.raises(ValueError, match="No pause"):
        api.pause_gcode(BAMBU.encode(), [])
