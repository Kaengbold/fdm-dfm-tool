"""Heat tuning prints (T-482): the sag and snap tests set the heat window for the user's printer."""

import numpy as np
import pytest

from fdmcore import api, gcode, kinematics, thermal
from fdmcore.mesh import load_stl
from fdmcore.profile import Profile, load_data

MIN_LAYER_S = 8.0  # the stand-in slicer's minimum layer time (it slows small layers down to it)


def loops(shape: list[tuple[float, float]], inset: float, n: int = 2) -> list[list[tuple[float, float]]]:
    """``n`` closed loops of a convex outline, each ``inset`` mm further in (walls)."""
    pts = np.asarray(shape, float)
    c = pts.mean(axis=0)
    out = []
    for k in range(n):
        d = pts - c
        scale = np.maximum(1 - (k + 0.5) * inset / np.maximum(np.linalg.norm(d, axis=1), 1e-9), 0.05)
        out.append([tuple(p) for p in c + d * scale[:, None]])
    return out


def fake_slice(shapes_at, height: float, fan: int = 255) -> str:
    """A stand-in for a slicer: per 0.2 mm layer, two wall loops of every outline ``shapes_at(z)`` returns, at
    200 mm/s, slowed down so a layer takes at least MIN_LAYER_S (OrcaSlicer's settings block says so)."""
    lh, w = 0.2, 0.45
    e_mm = w * lh / (np.pi * 1.75**2 / 4)
    out = ["; generated by OrcaSlicer", "M83", f"M106 S{fan}"]
    for k in range(int(round(height / lh))):
        z = (k + 1) * lh
        paths = [loop for shape in shapes_at(z - lh / 2) for loop in loops(shape, w)]
        length = sum(np.linalg.norm(np.diff(np.vstack([p, p[:1]]), axis=0), axis=1).sum() for p in paths)
        speed = 200.0 if k < 2 else max(min(200.0, length / MIN_LAYER_S), 10.0)
        out += [";LAYER_CHANGE", f"G1 Z{z:.2f} F600", "; FEATURE: Outer wall"]
        for p in paths:
            ring = p + p[:1]
            out.append(f"G1 X{ring[0][0] + 100:.3f} Y{ring[0][1] + 100:.3f} F9000")
            for (x0, y0), (x1, y1) in zip(ring, ring[1:]):
                out.append(f"G1 X{x1 + 100:.3f} Y{y1 + 100:.3f} E{np.hypot(x1 - x0, y1 - y0) * e_mm:.5f} F{speed * 60:.0f}")
    out += ["; outer_wall_speed = 200", "; inner_wall_speed = 200", "; initial_layer_speed = 200",
            "; slow_down_layer_time = 8", "; slow_down_min_speed = 10"]
    return "\n".join(out)


def circle(x: float, y: float, r: float, n: int = 16) -> list[tuple[float, float]]:
    a = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return list(zip(x + r * np.cos(a), y + r * np.sin(a)))


def sag_shapes(z: float):
    plate = [[(0, 0), (54, 0), (54, 14), (0, 14)]] if z < 2 else []
    return plate + [circle(6 + 10.5 * i, 10, 1.5) for i, h in enumerate(api.SAG_PINS_MM) if z < h]


def snap_shapes(z: float):
    return [[(0, -2.4), (80, -2.4), (80, 3.6), (0, 3.6)]] if z < 1 else [[(0, 0), (80, 0), (80, 1.2), (0, 1.2)]]


def test_the_test_parts():
    for kind, size in (("sag", (54, 14, 40)), ("snap", (80, 6, 40))):
        r = api.calibration_part(kind)
        lo, hi = load_stl(r["stl"]).bounds()
        assert np.allclose(hi - lo, size, atol=0.6) and "G-code" in r["how"]


def test_sag_test_gcode_switches_the_slowdown_off():
    text = fake_slice(sag_shapes, 40)
    r = api.tuning_gcode("sag", text.encode())
    before, after = gcode.parse(text), gcode.parse(r["data"].decode())
    top = before.layer_z[before.layer] > 33  # only the tallest pin: the slicer slowed it a lot
    assert (before.cause[top] == gcode.LAYER_TIME).all() and (after.speed[top] > 2 * before.speed[top]).all()
    assert r["minutes"][1] < r["minutes"][0]


def test_snap_test_gcode_steps_the_fan_down():
    text = fake_slice(snap_shapes, 40)
    back = gcode.parse(api.tuning_gcode("snap", text.encode())["data"].decode())
    z = back.layer_z[back.layer]
    for band, fan in enumerate(api.SNAP_FANS):
        sel = (z > band * api.SNAP_BAND_MM + 0.5) & (z < (band + 1) * api.SNAP_BAND_MM - 0.5)
        assert np.allclose(back.part_fan[sel], fan, atol=1 / 255)


def test_results_tune_the_window_and_the_label():
    """The sag test: the tallest pin drooped from 30 mm -> how hot it was there becomes the sag limit. The snap
    test: it held above 16 mm -> the bond there becomes the goal. Both in the profile: the window moves and
    the heat results say "tuned"."""
    sag_gcode = api.tuning_gcode("sag", fake_slice(sag_shapes, 40).encode())["data"]
    sag = api.tune_heat("sag", sag_gcode, 30.0)
    assert sag["field"] == "sag_limit_c" and 40 < sag["value"] < 200 and "30 mm" in sag["text"]
    none = api.tune_heat("sag", sag_gcode, None)
    assert none["value"] >= sag["value"]  # nothing drooped: the limit is at least as hot as the hottest spot
    snap = api.tune_heat("snap", api.tuning_gcode("snap", fake_slice(snap_shapes, 40).encode())["data"], 16.0)
    assert snap["field"] == "min_bond" and 0.02 <= snap["value"] <= 1
    with pytest.raises(ValueError, match="tuning_gcode"):
        api.tune_heat("sag", fake_slice(sag_shapes, 40).encode(), 30.0)  # the slicer's file, not the test G-code

    rough = Profile.from_dict({})
    tuned = Profile.from_dict({"heat_tuning": {"sag_limit_c": sag["value"], "min_bond": snap["value"]}})
    half = Profile.from_dict({"heat_tuning": {"sag_limit_c": sag["value"]}})
    assert [thermal.confidence(p) for p in (rough, half, tuned)] == ["rough", "partly tuned", "tuned"]
    tp = gcode.parse(sag_gcode)
    h = thermal.simulate(tp, kinematics.timing(tp), rough)
    w_rough, w_tuned = thermal.window(h, rough), thermal.window(h, tuned)
    shift = sag["value"] - (rough.material["softening_c"] + load_data("thresholds")["cooling"]["hot_margin_c"])
    assert np.allclose(w_tuned["limit_c"] - w_rough["limit_c"], shift, atol=1e-6)
    assert np.allclose(w_tuned["min_bond"], snap["value"])  # ordinary spots, balanced goal: the measured bond
    with pytest.raises(ValueError, match="heat_tuning min_bond"):
        Profile.from_dict({"heat_tuning": {"min_bond": 3}})


def test_my_material_carries_the_tuning():
    try:
        api.custom_presets(materials={"my_pla": {"based_on": "pla", "name": "My PLA", "sag_limit_c": 95, "min_bond": 0.3}})
        p = Profile.from_dict({"material": "my_pla"})
        assert p.heat_tuning == {"sag_limit_c": 95.0, "min_bond": 0.3} and thermal.confidence(p) == "tuned"
        assert Profile.from_dict({"material": "my_pla", "heat_tuning": {"min_bond": 0.5}}).heat_tuning["min_bond"] == 0.5
    finally:
        api.custom_presets(materials={})


def test_heat_results_say_whether_they_are_tuned():
    from pathlib import Path

    fixtures = Path(__file__).parent / "gcode"
    api.load((fixtures / "part.stl").read_bytes(), "fixture")
    api.load_gcode((fixtures / "bambu.gcode.3mf").read_bytes(), [0, 0, 1])
    assert api.heat_model([0, 0, 1])["confidence"] == "rough"
    tuned = {"heat_tuning": {"sag_limit_c": 120, "min_bond": 0.2}}
    assert api.heat_model([0, 0, 1], tuned)["confidence"] == "tuned"
    r = api.optimize_cooling([0, 0, 1], tuned)
    assert r["confidence"] == "tuned" and r["summary"][-1].startswith("Tuned to your printer")
