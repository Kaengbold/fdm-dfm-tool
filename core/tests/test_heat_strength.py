"""The heat model's bonding back in the strength check (T-476)."""

import numpy as np
import pytest

from fdmcore import api, thermal
from test_hold import box, region_facing

L, T, H, LH, W = 30.0, 1.8, 12.0, 0.2, 0.45  # a thin wall: 4 lines wide


def wall_gcode(fan: int, wait_s: float = 0) -> bytes:
    """The wall, line by line; ``wait_s``: the nozzle parks this long after each layer (as when many copies
    print at once), so each layer has cooled when the next one lands."""
    e = W * LH / (np.pi * 1.75**2 / 4)
    out = ["; generated by OrcaSlicer", "M83", f"M106 S{fan}"]
    for k in range(int(H / LH)):
        out += [";LAYER_CHANGE", f"G1 Z{(k + 1) * LH:.2f} F600", "; FEATURE: Outer wall"]
        for i, y in enumerate(np.arange(W / 2, T, W)):
            x0, x1 = (100, 100 + L) if i % 2 == 0 else (100 + L, 100)
            out += [f"G1 X{x0:.3f} Y{100 + y:.3f} F6000", f"G1 X{x1:.3f} Y{100 + y:.3f} E{L * e:.5f} F3000"]
        if wait_s:
            out += ["G1 X10 Y10 F12000", f"G4 S{wait_s:g}"]
    return "\n".join(out).encode()


@pytest.fixture(scope="module")
def wall():
    api.load(box(L, T, H), "wall")
    return [{"region": region_facing([0, 0, -1]), "kind": "fixed"},
            {"region": region_facing([0, 0, 1]), "kind": "force", "kg": 0.5, "direction": [0, 1, 0]}]


def test_an_overcooled_wall_is_weaker_than_one_printed_in_its_window(wall):
    """Bent across its layers: printed with long waits under full fan, the layers fuse poorly and the safety
    drops well below that of the same wall printed straight through at 30 % fan."""
    api.load_gcode(wall_gcode(fan=77), [0, 0, 1])
    good = api.strength([0, 0, 1], wall, detailed=True, heat=True)
    api.load_gcode(wall_gcode(fan=255, wait_s=30), [0, 0, 1])
    cold = api.strength([0, 0, 1], wall, detailed=True, heat=True)
    assert cold["safety_factor"] < 0.7 * good["safety_factor"]
    assert cold["mode"] == "layers" and cold["heat"]["bond_at_weakest"] < 0.7
    assert cold["heat"]["usual_safety_factor"] == pytest.approx(good["heat"]["usual_safety_factor"], rel=0.02)
    assert "weakens the layers" in cold["heat"]["text"] and "instead of" in cold["heat"]["text"]
    plain = api.strength([0, 0, 1], wall, detailed=True)  # without the heat option: one value for the whole part
    assert "heat" not in plain and plain["safety_factor"] == pytest.approx(cold["heat"]["usual_safety_factor"])


def test_heat_needs_the_detailed_check(wall):
    with pytest.raises(ValueError, match="detailed"):
        api.strength([0, 0, 1], wall, heat=True)


def test_bond_strength_scale():
    usual = thermal.load_data("thermal")["strength"]["usual_bond"]
    out = thermal.bond_strength(np.array([usual, usual / 2, 0.0, 1.0, np.nan]), most=1.1)
    assert out == pytest.approx([1.0, 0.5, thermal.load_data("thermal")["strength"]["min_share"], 1.1, 1.0])
