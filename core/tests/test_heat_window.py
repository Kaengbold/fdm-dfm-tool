"""The temperature window (T-474): too hot to keep its shape, too cold to bond, slowdowns that aren't needed."""

import gzip
from pathlib import Path

import numpy as np
import pytest

from fdmcore import api, gcode, kinematics, thermal
from fdmcore.profile import Profile

FIXTURES = Path(__file__).parent / "gcode"
PIN_Z = 6.4  # above this only the Ø3 mm pin of the fixture part prints


def profile(goal: str = "balanced") -> Profile:
    return Profile.from_dict({"material": "pla", "printer": "bambu_p1s", "goal": goal})


@pytest.fixture(scope="module")
def fixture_heat():
    tp = gcode.parse(gzip.decompress((FIXTURES / "orca.gcode.gz").read_bytes()))
    return tp, thermal.simulate(tp, kinematics.timing(tp), profile())


def slab(fan: int = 255, speed: float = 50, set_speed: float | None = None, length: float = 60.0, thick: float = 6.0) -> str:
    """A thick wall (solid, ``thick`` mm), 25 layers, lines along it at ``speed`` mm/s, fan at ``fan``/255.
    ``set_speed``: an OrcaSlicer settings block saying the lines were set faster (so they count as slowed
    down for layer cooling)."""
    w, lh = 0.45, 0.2
    e = w * lh / (np.pi * 1.75**2 / 4)
    out = ["; generated by OrcaSlicer", "M83", f"M106 S{fan}"]
    for k in range(25):
        out += [";LAYER_CHANGE", f"G1 Z{(k + 1) * lh:.2f} F600", "; FEATURE: Inner wall"]
        for i, y in enumerate(np.arange(w / 2, thick, w)):
            x0, x1 = (0, length) if i % 2 == 0 else (length, 0)
            out += [f"G1 X{x0:.3f} Y{y:.3f} F6000", f"G1 X{x1:.3f} Y{y:.3f} E{length * e:.5f} F{speed * 60:.0f}"]
    if set_speed:
        out += [f"; {k} = {set_speed:g}" for k in ("outer_wall_speed", "inner_wall_speed", "sparse_infill_speed",
                                                     "internal_solid_infill_speed")]
        out += ["; slow_down_layer_time = 30", f"; slow_down_min_speed = {speed:g}"]
    return "\n".join(out)


def judged(text: str, goal: str = "balanced", load_bearing: bool = False):
    tp = gcode.parse(text)
    h = thermal.simulate(tp, kinematics.timing(tp), profile(goal))
    intents = {"load_bearing": np.ones(len(h.layer), bool)} if load_bearing else None
    return h, thermal.window(h, profile(goal), intents)


def test_thin_pin_is_too_hot_and_the_block_passes(fixture_heat):
    _, h = fixture_heat
    w = thermal.window(h, profile())
    pin = h.z > 6.0  # the block is 6 mm tall
    assert w["too_hot"][h.z > PIN_Z].all()
    assert not w["too_hot"][~pin].any()
    assert not w["too_cold"].any() and not w["needless"].any()  # the block, its tab and the pin bond well enough


def test_thick_load_bearing_wall_under_full_fan_is_too_cold():
    h, w = judged(slab(fan=255), load_bearing=True)
    body = h.layer >= 5
    assert w["too_cold"][body].mean() > 0.8
    assert not w["too_hot"].any()
    _, gentle = judged(slab(fan=77), load_bearing=True)  # same wall at 30 % fan: warm enough to bond
    assert not gentle["too_cold"][h.layer >= 5].any()


def test_goals_move_the_window(fixture_heat):
    _, h = fixture_heat
    fast, strong = thermal.window(h, profile("speed")), thermal.window(h, profile("strength"))
    assert (fast["limit_c"] > strong["limit_c"]).all() and (fast["min_bond"] < strong["min_bond"]).all()  # fast accepts more droop
    assert strong["too_cold"].sum() >= fast["too_cold"].sum() and strong["too_hot"].sum() >= fast["too_hot"].sum()


def test_cosmetic_spots_get_a_stricter_sag_limit(fixture_heat):
    _, h = fixture_heat
    everywhere = np.ones(len(h.layer), bool)
    plain, cosmetic = thermal.window(h, profile()), thermal.window(h, profile(), {"cosmetic": everywhere})
    assert (cosmetic["limit_c"] < plain["limit_c"]).all()


def test_bridges_and_overhangs_get_a_stricter_sag_limit(fixture_heat):
    _, h = fixture_heat
    w = thermal.window(h, profile())
    spans = h.overhang >= 0.5
    assert spans.any() and (w["limit_c"][spans] < w["limit_c"][~spans].min()).all()


def test_slowing_down_a_cold_wall_is_needless():
    """The slicer slowed every line of a load-bearing wall (set 200 mm/s, printed at 20 for layer cooling), yet
    it ends up too cold to bond as well as it should: that slowdown wasn't needed."""
    h, w = judged(slab(fan=255, speed=20, set_speed=200), load_bearing=True)
    assert (h.cooled[h.layer >= 1] > 0.9).all()  # the first layer has its own speed
    assert w["needless"][h.layer >= 5].mean() > 0.8


def test_heat_model_findings_in_plain_words():
    api.load((FIXTURES / "part.stl").read_bytes(), "fixture")
    api.load_gcode((FIXTURES / "bambu.gcode.3mf").read_bytes(), [0, 0, 1])
    r = api.heat_model([0, 0, 1])
    hot = [f for f in r["findings"] if f["rule"] == "heat_too_hot"]
    assert hot and all(f["bbox"][0][2] > 6 for f in hot)  # the pin, not the block
    assert {f["rule"] for f in r["findings"]} == {"heat_too_hot"}
    assert "sag or blob" in hot[0]["detail"] and "°C" in hot[0]["detail"]
    explained = api.explain_finding(hot[0], "print")
    assert explained["fixes"] and explained["fixes"][0]["domain"] == "slicer"
    window = np.frombuffer(r["window"], np.uint8)
    assert len(window) == r["spots"] and set(np.unique(window)) == {0, 1}
    with pytest.raises(ValueError, match="design intent"):
        api.heat_model([0, 0, 1], intents=[{"kind": "pretty", "point": [0, 0, 5], "radius": 3}])
